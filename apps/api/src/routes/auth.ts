/**
 * Login, logout and "who am I" (HANDOFF section 9).
 *
 * Accounts are created with the CLI, not by signing up: this is a two-person
 * household app and there is no registration route to attack.
 */
import { randomUUID } from "node:crypto";
import type { FastifyInstance } from "fastify";
import { z } from "zod";
import { hashPassword, verifyPassword } from "../auth/password.js";
import { endSession, startSession } from "../auth/session.js";

const loginBody = z.object({
  email: z.string().trim().min(1, "Enter your email.").max(320).toLowerCase(),
  password: z.string().min(1, "Enter your password."),
});

/**
 * A hash to verify against when the email does not exist, so that a wrong
 * email and a wrong password cost the same time and cannot be told apart.
 *
 * Generated by hashing a random value on first use rather than hard-coded: a
 * hand-written PHC string that turned out to be malformed would fail fast
 * instead of doing the work, which is exactly the timing difference this is
 * meant to remove.
 */
let dummyHash: Promise<string> | undefined;
function getDummyHash(): Promise<string> {
  dummyHash ??= hashPassword(`${randomUUID()}${randomUUID()}`);
  return dummyHash;
}

export async function registerAuthRoutes(app: FastifyInstance): Promise<void> {
  app.post(
    "/auth/login",
    {
      config: {
        rateLimit: {
          max: app.env.LOGIN_RATE_LIMIT,
          timeWindow: "15 minutes",
          // Per IP, as documented for LOGIN_RATE_LIMIT in .env.example.
          keyGenerator: (request) => request.ip,
        },
      },
    },
    async (request, reply) => {
      const parsed = loginBody.safeParse(request.body);
      if (!parsed.success) {
        return reply.status(400).send({
          error: "invalid_request",
          message: parsed.error.issues[0]?.message ?? "Check your email and password.",
        });
      }

      const { email, password } = parsed.data;

      const user = await app.db.prisma.user.findFirst({
        where: { email, deletedAt: null },
      });

      // Always run a verification, even with no such user, to keep the timing
      // and the response indistinguishable.
      const hashToCheck = user?.passwordHash ?? (await getDummyHash());
      const ok = await verifyPassword(hashToCheck, password);

      if (!user || !ok) {
        request.log.info({ email, ip: request.ip }, "failed login");
        return reply.status(401).send({
          error: "invalid_credentials",
          message: "That email and password do not match.",
        });
      }

      await startSession(app.db.prisma, app.env, reply, user.id, request);
      request.log.info({ userId: user.id }, "signed in");

      return reply.send({
        user: {
          id: user.id,
          householdId: user.householdId,
          name: user.name,
          initial: user.initial,
          email: user.email,
          colorFg: user.colorFg,
          colorBg: user.colorBg,
        },
      });
    },
  );

  app.post("/auth/logout", async (request, reply) => {
    await endSession(app.db.prisma, app.env, request, reply);
    return reply.send({ ok: true });
  });

  app.get("/me", async (request, reply) => {
    if (!request.user) {
      return reply.status(401).send({ error: "not_signed_in", message: "Sign in to continue." });
    }

    // The household's settings travel with the user: the web app needs the
    // cushion, horizon and weekend rule to run the engine locally for instant
    // feedback while editing.
    const household = await app.db.prisma.household.findUnique({
      where: { id: request.user.householdId },
      select: {
        id: true,
        name: true,
        timezone: true,
        currency: true,
        cushionCents: true,
        horizonRule: true,
        horizonPaychequeCount: true,
        weekendWithdrawalRule: true,
        version: true,
      },
    });

    const members = await app.db.prisma.user.findMany({
      where: { householdId: request.user.householdId, deletedAt: null },
      select: { id: true, name: true, initial: true, colorFg: true, colorBg: true },
      orderBy: { name: "asc" },
    });

    return reply.send({ user: request.user, household, members });
  });
}
